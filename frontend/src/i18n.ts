// o "pl", a nie o "en": brak zapisanej wartosci ma znaczyc angielski.
// Ta sama zasada obowiazuje przy wyborze jezyka pomocy (`desktop/help.ts`).
const initialLanguage = storedLanguage === "pl" ? "pl" : "en";

void i18n.use(initReactI18next).init({
  resources: {
    pl: { translation: { ...polishTranslations, ...polishInfoTranslations, ...polishDynamicTranslations, ...polishSceneImportTranslations, ...polishSamModelTranslations, ...polishTrainingWorkbenchTranslations } },
    en: { translation: { ...englishTranslations, ...englishInfoTranslations, ...englishSamModelTranslations, ...englishTrainingWorkbenchTranslations } }
  },
  lng: initialLanguage,
  fallbackLng: "en",
  keySeparator: false,
  interpolation: { escapeValue: false },
  returnNull: false
});

i18n.on("languageChanged", (language) => {
  if (typeof window !== "undefined") {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language.startsWith("pl") ? "pl" : "en");
  }
  if (typeof document !== "undefined") {
    document.documentElement.lang = language.startsWith("pl") ? "pl" : "en";
  }
});

if (typeof document !== "undefined") {
  document.documentElement.lang = initialLanguage;
}

